"""Import public source locations, never stops, timetables or terminal entrances.

python scripts/build-mexico-places.py airports.csv mexico.poly
Sources: https://ourairports.com/data/ (Public Domain),
https://download.geofabrik.de/north-america/mexico.poly (OSM / ODbL).
"""
import csv, datetime, hashlib, json, pathlib, sys

root = pathlib.Path(__file__).resolve().parents[1]
airports, polygon = map(pathlib.Path, sys.argv[1:])
rows = []
for r in csv.DictReader(airports.open(encoding="utf-8")):
    if r["iso_country"] != "MX" or r["scheduled_service"] != "yes" or not r["iata_code"]:
        continue
    rows.append({"ident": r["ident"], "iata": r["iata_code"], "name": r["name"],
                 "locality": r["municipality"], "lat": float(r["latitude_deg"]),
                 "lon": float(r["longitude_deg"]), "keywords": r["keywords"]})
rings, ring = [], None
for line in polygon.read_text().splitlines()[1:]:
    parts = line.split()
    if not parts:
        continue
    if parts == ["END"]:
        if ring:
            rings.append(ring)
        ring = None
    elif len(parts) == 1:
        ring = {"exclude": parts[0].startswith("!"), "points": []}
    elif ring is not None:
        ring["points"].append(list(map(float, parts)))
for name, value, note in [("mexico-airports-data.mjs", rows, "OurAirports, Public Domain; reference points, not boarding stops"),
                          ("mexico-search-area.mjs", rings, "Geofabrik / OpenStreetMap, ODbL; source extract area, not a certified country boundary")]:
    (root / "lib" / name).write_text("// " + note + "; generated by scripts/build-mexico-places.py\nexport default " + json.dumps(value, ensure_ascii=False, separators=(",", ":")) + ";\n")
meta = {"retrieved": datetime.date.today().isoformat(), "airports": len(rows),
        "sources": [{"url": "https://ourairports.com/data/airports.csv", "license": "Public Domain", "sha256": hashlib.sha256(airports.read_bytes()).hexdigest()},
                    {"url": "https://download.geofabrik.de/north-america/mexico.poly", "license": "ODbL-1.0", "sha256": hashlib.sha256(polygon.read_bytes()).hexdigest()}],
        "notes": "Airport reference coordinates do not confirm a terminal entrance, pedestrian access or timetable. The search polygon excludes distant foreign matches; no country is inferred for native timetable stops."}
(root / "public/data/mexico-places-sources.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n")
print(json.dumps({"airports": len(rows), "rings": len(rings)}))
